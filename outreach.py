"""Outreach: send demo email to S's OWN inbox via gog gmail, schedule follow-up.

SAFETY RULE: outreach is never sent to the discovered lead's real address.
The discovered contact is quoted in the body for realism; the actual recipient
is always the configured test inbox (OUTREACH_TO, default GOG_ACCOUNT).
"""
import datetime as dt
import logging

import sheets
from config import cfg

log = logging.getLogger("agent.outreach")

FOLLOWUP_DAYS = 3


def _gog(args, timeout=60):
    exe = cfg("GOG_EXE", "gog")
    cmd = [exe] + args
    account = cfg("GOG_ACCOUNT")
    if account:
        cmd += ["-a", account]
    log.info("gog %s", " ".join(args[:2]))
    return subprocess_run(cmd, timeout)


def subprocess_run(cmd, timeout):
    import subprocess
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def test_inbox():
    return cfg("OUTREACH_TO") or cfg("GOG_ACCOUNT")


def outreach_email(lead, company, city, pitch):
    """Build (subject, body) for the demo outreach email."""
    subject = f"[DEMO] Event partnership idea for {company} ({city})"
    contact_line = lead.get("email") or lead.get("linkedin") or "no public contact found"
    body = (
        f"DEMO RUN — this email goes to the operator's own test inbox, "
        f"NOT to the real lead.\n\n"
        f"Intended recipient: {lead.get('name', 'Unknown')} "
        f"({lead.get('role', 'Unknown')}, {company}) — contact on file: {contact_line}\n\n"
        f"--- PITCH ---\n{pitch}\n\n"
        f"--- META ---\nCompany: {company}\nCity: {city}\n"
        f"Generated by lead-outreach-agent (screening assignment demo)."
    )
    return subject, body


def send_outreach(lead, company, city, pitch):
    """Send the demo email to the test inbox. Returns (sent: bool, message_id_or_error)."""
    to = test_inbox()
    if not to:
        log.error("no test inbox configured (OUTREACH_TO/GOG_ACCOUNT)")
        return False, "no test inbox configured"
    subject, body = outreach_email(lead, company, city, pitch)
    res = _gog([
        "gmail", "send",
        "--to", to,
        "--subject", subject,
        "--body", body,
        "--no-input",
    ])
    if res.returncode != 0:
        err = res.stderr.strip()[:300]
        log.error("gmail send failed: %s", err)
        return False, err
    out = (res.stdout or "").strip()
    log.info("outreach sent to %s", to)
    return True, out.splitlines()[0] if out else "sent"


def followup_date(days=FOLLOWUP_DAYS):
    return (dt.date.today() + dt.timedelta(days=days)).isoformat()


def process_followups(today=None, send=True):
    """Scan the Sheet for due follow-ups and send the follow-up email.

    A row is due when Outreach Sent=YES, Follow-up Date <= today, and no
    follow-up marker yet (Status stays 'Enriched'; we mark via a second send
    and update Follow-up Date to '' after processing — simple and visible).
    Returns list of dicts describing actions.
    """
    today = today or dt.date.today().isoformat()
    actions = []
    for row_num, cells in sheets.find_rows():
        # columns: 0 Date 1 Company 2 City 3 Status 4 Lead 5 Role 6 Contact
        #          7 LinkedIn 8 Pitch 9 Outreach Sent 10 Follow-up Date
        if len(cells) < 11:
            continue
        sent, due, status = cells[9].strip(), cells[10].strip(), cells[3].strip()
        if sent.upper() != "YES" or not due or due > today or status.startswith("Followed up"):
            continue
        company, city = cells[1], cells[2]
        pitch = cells[8]
        subject = f"[DEMO][Follow-up] Re: Event partnership idea for {company} ({city})"
        body = (
            f"DEMO RUN — follow-up email to the operator's own test inbox, NOT the real lead.\n\n"
            f"Following up on the pitch for {company} ({city}):\n\n{pitch}\n"
        )
        if send:
            res = _gog(["gmail", "send", "--to", test_inbox(), "--subject", subject,
                        "--body", body, "--no-input"])
            ok = res.returncode == 0
            detail = "sent" if ok else res.stderr.strip()[:200]
        else:
            ok, detail = True, "dry-run (not sent)"
        if ok and send:
            # Mark the row so the next scan doesn't re-send
            try:
                sheets.update_row(row_num, 3, [f"Followed up on {today}"])
            except Exception as exc:
                log.warning("could not mark row %d as followed up: %s", row_num, exc)
        actions.append({"row": row_num, "company": company, "city": city,
                        "due": due, "sent": ok, "detail": detail})
    return actions
